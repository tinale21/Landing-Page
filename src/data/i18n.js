/**
 * Interface translations.
 *
 * The official site offers four languages (EN / AR / RU / ZH). This covers
 * twelve, chosen for Dubai's largest inbound visitor markets.
 *
 * SCOPE, deliberately limited: interface chrome only — navigation, headings,
 * buttons, tabs, menu. Long-form factual content (FAQ answers, venue
 * descriptions, construction milestones, opening hours) stays in English and
 * is covered by the `englishNote` string.
 *
 * That boundary is on purpose. The FAQ carries accessibility facts — service
 * animals are not permitted, strollers must be checked — where a translation
 * error could send a disabled visitor on a trip they cannot complete. Those
 * need a human translator, not this.
 *
 * NO RTL MIRRORING. Arabic and Urdu read right-to-left, and the official site
 * mirrors its layout for them (verified on burjkhalifa.ae/ar/ — logo right,
 * Book Tickets left). The designer chose to translate without mirroring, so
 * `dir` stays `ltr` in every language and the composition never moves. This is
 * a known, deliberate departure from correct RTL behaviour.
 */
